using UnrealBuildTool;
using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Security.Cryptography;
using System.Diagnostics;
using System.Text.Json;
using System.Text.RegularExpressions;

public class ImperialWingsSimulator : ModuleRules
{
    public ImperialWingsSimulator(ReadOnlyTargetRules Target) : base(Target)
    {
        PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;
        PublicDependencyModuleNames.AddRange(new string[]
        {
            "Core",
            "CoreUObject",
            "Engine",
            "InputCore",
            "EnhancedInput"
            , "HTTP", "Json", "JsonUtilities", "PhysicsCore"
        });
        bUseUnity = false;
        PrivateDependencyModuleNames.Add("Chaos");
        if (Target.Platform == UnrealTargetPlatform.Win64) PublicSystemLibraries.Add("winmm.lib");
        WriteBuildIdentity(Target);
    }

    private void WriteBuildIdentity(ReadOnlyTargetRules Target)
    {
        string Root = Path.GetFullPath(Path.Combine(ModuleDirectory, "../.."));
        string[] Folders = { "Source", "Config", "Content", "ArtSource", "Bridge", "Scripts" };
        string[] Extensions = { ".h", ".cpp", ".cs", ".ini", ".json", ".py", ".ps1", ".txt", ".cmd", ".bat", ".uproject", ".uasset", ".umap", ".png" };
        string[] Binary = { ".uasset", ".umap", ".png" };
        var Inputs = Folders.Where(F => Directory.Exists(Path.Combine(Root,F)))
            .SelectMany(F => Directory.EnumerateFiles(Path.Combine(Root,F), "*", SearchOption.AllDirectories))
            .Where(F => Extensions.Contains(Path.GetExtension(F).ToLowerInvariant()))
            .Concat(Directory.EnumerateFiles(Root).Where(F => new[] { ".uproject", ".cmd" }.Contains(Path.GetExtension(F).ToLowerInvariant())))
            .Select(F => Path.GetRelativePath(Root,F).Replace('\\','/')).OrderBy(F => F,StringComparer.Ordinal).ToArray();
        var Manifest = new StringBuilder();
        foreach(string Relative in Inputs)
        {
            string Full = Path.Combine(Root,Relative);
            byte[] Bytes = Binary.Contains(Path.GetExtension(Full).ToLowerInvariant()) ? File.ReadAllBytes(Full)
                : Encoding.UTF8.GetBytes(File.ReadAllText(Full).Replace("\r\n","\n"));
            Manifest.Append(Relative).Append('\0').Append(Hash(Bytes)).Append('\n');
            ExternalDependencies.Add(Full);
        }
        foreach(string Folder in Folders) ExternalDependencies.Add(Path.Combine(Root,Folder));
        foreach(string GitFile in new[]{".git/HEAD",".git/refs/heads/main",".git/packed-refs"})
            if(File.Exists(Path.Combine(Root,GitFile)))ExternalDependencies.Add(Path.Combine(Root,GitFile));
        string SourceHash = Hash(Encoding.UTF8.GetBytes(Manifest.ToString()));
        string Commit = Git(Root,"rev-parse HEAD");
        if(!Regex.IsMatch(Commit,"^[a-f0-9]{40}$"))Commit="unknown";
        string Dirty = Git(Root,"status --porcelain -- Source Config Content ArtSource Bridge Scripts ImperialWingsSimulator.uproject ImperialWings.cmd");
        string Settings = File.ReadAllText(Path.Combine(Root,"Config/DefaultGame.ini"));
        var VersionMatch = Regex.Match(Settings,@"(?m)^ProjectVersion=([^\r\n]+)");
        string Version = VersionMatch.Success ? VersionMatch.Groups[1].Value.Trim() : "unversioned";
        string Output = Path.Combine(Root,"Intermediate/Build/ImperialBuildIdentity",Target.Name+"-"+Target.Platform+"-"+Target.Configuration);
        Directory.CreateDirectory(Output);
        string JsonPath = Path.Combine(Output,"ImperialBuildIdentity.json");
        string BuiltAt = DateTime.UtcNow.ToString("yyyy-MM-ddTHH:mm:ssZ");
        if(File.Exists(JsonPath))
        {
            string Existing=File.ReadAllText(JsonPath);
            var Stamp=Regex.Match(Existing,"\"build_utc\"\\s*:\\s*\"([0-9TZ:-]{20})\"");
            if(Existing.Contains("\"source_sha256\": \""+SourceHash+"\"") && Existing.Contains("\"source_commit\": \""+Commit+"\"") &&
               Existing.Contains("\"source_dirty\": "+(string.IsNullOrEmpty(Dirty)?"false":"true")) && Stamp.Success)BuiltAt=Stamp.Groups[1].Value;
        }
        var Identity = new { version=Version,source_commit=Commit,source_dirty=!string.IsNullOrEmpty(Dirty),source_sha256=SourceHash,
            build_utc=BuiltAt,target=Target.Name,platform=Target.Platform.ToString(),configuration=Target.Configuration.ToString(),input_count=Inputs.Length };
        string Json = JsonSerializer.Serialize(Identity,new JsonSerializerOptions{WriteIndented=true});
        WriteChanged(JsonPath,Json);
        string Header = "// Generated by UnrealBuildTool from the actual build inputs.\n#pragma once\n";
        foreach(var Entry in new[]{("VERSION",Version),("COMMIT",Commit),("SOURCE_SHA256",SourceHash),("UTC",BuiltAt),("TARGET",Target.Name)})
            Header+="#define IW_BUILD_"+Entry.Item1+" "+JsonSerializer.Serialize(Entry.Item2)+"\n";
        Header+="#define IW_BUILD_DIRTY "+(string.IsNullOrEmpty(Dirty)?"0":"1")+"\n";
        WriteChanged(Path.Combine(Output,"ImperialBuildIdentity.generated.h"),Header);
        PrivateIncludePaths.Add(Output);
        RuntimeDependencies.Add("$(BinaryOutputDir)/ImperialBuildIdentity-"+Target.Name+".json",JsonPath,StagedFileType.NonUFS);
    }

    private static string Hash(byte[] Value)
    {
        using var Sha = SHA256.Create();
        return BitConverter.ToString(Sha.ComputeHash(Value)).Replace("-","").ToLowerInvariant();
    }
    private static string Git(string Root,string Arguments)
    {
        try
        {
            using var P = Process.Start(new ProcessStartInfo("git",Arguments){WorkingDirectory=Root,UseShellExecute=false,CreateNoWindow=true,RedirectStandardOutput=true,RedirectStandardError=true});
            if(P==null)return "";
            string Result=P.StandardOutput.ReadToEnd();
            if(!P.WaitForExit(3000)||P.ExitCode!=0)return "";
            return Result.Trim();
        }
        catch(Exception E) when(E is System.ComponentModel.Win32Exception || E is InvalidOperationException){return "";}
    }
    private static void WriteChanged(string PathName,string Value)
    {
        if(!File.Exists(PathName)||File.ReadAllText(PathName)!=Value)File.WriteAllText(PathName,Value,new UTF8Encoding(false));
    }
}
